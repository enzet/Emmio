r"""Shared TikZ (pgfplots) rendering for rate estimate trajectory plots.

The visualizer (`emmio.lexicon.visualize`) can render the simulation
and replay trajectories not only as images but also as TikZ code, ready
to be embedded into a LaTeX document (e.g. with `\input`). The
picture mirrors the Matplotlib style of `emmio.lexicon.plotting`: the
same method colors, recessive chrome, and direct labels at line ends.

The generated fragment is a `tikzpicture` built on pgfplots and needs

    \usepackage{pgfplots}
    \pgfplotsset{compat=1.18}

in the document preamble. Axis dimensions are relative to
`\linewidth`, so the picture adapts to the embedding document.
"""

import math
from collections.abc import Sequence

from emmio.lexicon.config import LexiconSelection
from emmio.lexicon.core import RATE_ESTIMATOR_BY_SELECTION, RateEstimator
from emmio.lexicon.plotting import (
    GRID_COLOR,
    METHOD_COLORS,
    spread_label_positions,
)
from emmio.lexicon.simulation import (
    CheckpointStats,
    MethodTrajectory,
    aggregate_trajectories,
)

__author__ = "Sergey Vartanov"
