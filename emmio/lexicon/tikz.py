CHROME_COLORS: dict[str, str] = {"emmiogrid": GRID_COLOR}
"""Chart chrome colors of `emmio.lexicon.plotting` as xcolor names."""

AXIS_CHROME: list[str] = [
    # Everything drawn is inside the computed axis limits; clipping off
    # lets direct labels overflow the axis to the right, as designed.
    "clip=false",
    "axis lines=left",
    "ticklabel style={font=\\footnotesize}",
    "xlabel={queries}",
    "xlabel style={font=\\footnotesize}",
    "ymajorgrids",
    "grid style={emmiogrid, line width=0.6pt}",
    "title style={font=\\footnotesize, at={(0,1.02)}, anchor=south west}",
]
"""Recessive axis chrome, the pgfplots twin of `plotting.style_axis`."""


def method_color_name(estimator: RateEstimator) -> str:
    """Get the xcolor name of a checking method's color.

    :param estimator: rate estimator identifying the method
    :return: xcolor name defined by the generated preamble
    """
    return f"emmio{estimator}"


def _preamble(estimators: list[RateEstimator]) -> list[str]:
    """Build the comment header and the color definitions.

    :param estimators: methods whose colors the picture uses
    :return: lines preceding the `tikzpicture` environment
    """
    colors: dict[str, str] = dict(CHROME_COLORS)
    for estimator in estimators:
        colors[method_color_name(estimator)] = METHOD_COLORS[estimator]
    return [
        "% Generated by `emmio.lexicon.visualize`; do not edit.",
        "% Requires `\\usepackage{pgfplots}` and "
        "`\\pgfplotsset{compat=1.18}` in the preamble.",
        *(
            f"\\definecolor{{{name}}}{{HTML}}"
            f"{{{hex_color.lstrip('#').upper()}}}"
            for name, hex_color in colors.items()
        ),
    ]


def _begin_axis(options: list[str]) -> list[str]:
    r"""Format a `\begin{axis}[...]` block with one option per line."""
    return ["\\begin{axis}[", *(f"    {option}," for option in options), "]"]


def _coordinates(points: Sequence[tuple[float, float]]) -> str:
    """Format points as a pgfplots coordinate list."""
    return " ".join(f"({x:g},{y:.4f})" for x, y in points)


def _segments(
    checkpoints: list[int], values: list[float]
) -> list[list[tuple[float, float]]]:
    """Split a trajectory into contiguous runs without gaps.

    pgfplots has no NaN-gap idiom as natural as Matplotlib's, so gaps
    (NaN values) split a trajectory into separately drawn runs.

    :param checkpoints: query numbers of the checkpoints
    :param values: per-checkpoint values, NaN marking the gaps
    :return: runs of (query number, value) pairs between the gaps
    """
    segments: list[list[tuple[float, float]]] = []
    current: list[tuple[float, float]] = []
    for x, value in zip(checkpoints, values, strict=True):
        if math.isnan(value):
            if current:
                segments.append(current)
                current = []
        else:
            current.append((float(x), value))
    if current:
        segments.append(current)
    return segments


def _estimate_segments(
    checkpoints: list[int], estimates: list[tuple[float, float] | None]
) -> list[list[tuple[float, float, float]]]:
    """Split an estimate trajectory into contiguous runs without gaps.

    :param checkpoints: query numbers of the checkpoints
    :param estimates: per-checkpoint (r̂, SD), or None where the
        estimator had no answer
    :return: runs of (query number, r̂, SD) triples between the gaps
    """
    segments: list[list[tuple[float, float, float]]] = []
    current: list[tuple[float, float, float]] = []
    for x, estimate in zip(checkpoints, estimates, strict=True):
        if estimate is None:
            if current:
                segments.append(current)
                current = []
        else:
            current.append((float(x), estimate[0], estimate[1]))
    if current:
        segments.append(current)
    return segments


def _plot_segments(
    checkpoints: list[int], values: list[float], options: str
) -> list[str]:
    r"""Draw a possibly gapped trajectory as one plot per contiguous run.

    Runs of a single point are skipped: a line through one point is
    invisible, which matches how Matplotlib renders NaN neighbors.

    :param checkpoints: query numbers of the checkpoints
    :param values: per-checkpoint values, NaN marking the gaps
    :param options: pgfplots plot options
    :return: `\addplot` lines
    """
    return [
        f"\\addplot[{options}] coordinates\n    {{{_coordinates(segment)}}};"
        for segment in _segments(checkpoints, values)
        if len(segment) > 1
    ]


def _end_label(x: float, y: float, label: str, options: str) -> str:
    """Format a direct label node to the right of a line end.

    :param x: x coordinate of the line end
    :param y: y position of the label
    :param label: label text, inserted verbatim (may contain math)
    :param options: additional node options
    """
    return (
        f"\\node[anchor=west, xshift=4pt, {options}] "
        f"at (axis cs:{x:g},{y:.4f}) {{{label}}};"
    )


def render_replay(
    checkpoints: list[int],
    estimates: list[tuple[float, float] | None],
    selection: LexiconSelection,
    title: str | None,
) -> str:
    """Render the replayed estimate trajectory as TikZ code.

    The same picture as `visualize.plot_replay`, without the "don't
    know" marks: the r̂ line with its ±1 SD band in the method's color,
    and the last estimate direct-labeled at the line end.

    :param checkpoints: query numbers of the checkpoints
    :param estimates: per-checkpoint (r̂, SD), or None where the
        estimator had no answer
    :param selection: the lexicon's selection strategy, for the color
    :param title: axis title, inserted verbatim (may contain math), or
        None for no title
    :return: LaTeX code of the `tikzpicture`
    """
    estimator: RateEstimator = RATE_ESTIMATOR_BY_SELECTION[selection]
    color: str = method_color_name(estimator)

    bounds: list[float] = [
        r_hat + sign * sd
        for estimate in estimates
        if estimate is not None
        for r_hat, sd in (estimate,)
        for sign in (-1.0, 1.0)
    ]
    y_low: float = min(bounds, default=0.0)
    y_high: float = max(bounds, default=1.0)
    pad: float = 0.05 * ((y_high - y_low) or 1.0)
    y_min: float = y_low - pad
    x_last: float = float(checkpoints[-1])

    # Direct labels overflow the axis to the right, so the axis leaves
    # them a share of the line width.
    options: list[str] = [
        "width=.85\\linewidth",
        "height=.42\\linewidth",
        *AXIS_CHROME,
        f"xmin=0, xmax={x_last * 1.18:.1f}",
        f"ymin={y_min:.4f}, ymax={y_high + pad:.4f}",
    ]
    if title is not None:
        options.append(f"title={{{title}}}")

    lines: list[str] = [
        *_preamble([estimator]),
        "\\begin{tikzpicture}",
        *_begin_axis(options),
    ]

    # The ±1 SD band: a closed polygon (upper edge, then the lower edge
    # backwards) per contiguous run of estimates.
    for segment in _estimate_segments(checkpoints, estimates):
        if len(segment) < 2:
            continue
        upper: list[tuple[float, float]] = [
            (x, r_hat + sd) for x, r_hat, sd in segment
        ]
        lower: list[tuple[float, float]] = [
            (x, r_hat - sd) for x, r_hat, sd in reversed(segment)
        ]
        lines += [
            f"\\addplot[draw=none, fill={color}, fill opacity=0.15, "
            "forget plot] coordinates",
            f"    {{{_coordinates(upper + lower)}}} -- cycle;",
        ]

    lines += _plot_segments(
        checkpoints,
        [
            estimate[0] if estimate is not None else math.nan
            for estimate in estimates
        ],
        f"{color}, line width=1.2pt",
    )

    last: tuple[float, float] | None = next(
        (estimate for estimate in reversed(estimates) if estimate is not None),
        None,
    )
    if last is not None:
        r_hat, sd = last
        lines.append(
            _end_label(
                x_last,
                r_hat,
                f"$\\hat{{r}} = {r_hat:.2f} \\pm {sd:.2f}$",
                "font=\\footnotesize",
            )
        )

    lines += ["\\end{axis}", "\\end{tikzpicture}", ""]
    return "\n".join(lines)


def render_simulation(
    methods: list[LexiconSelection],
    trajectories: dict[LexiconSelection, list[MethodTrajectory]],
    true_rates: list[float],
    tolerance: float,
) -> str:
    """Render the convergence process as TikZ code.

    The same picture as `visualize.plot_simulation`: the left axis with
    every trial's estimate trajectory (thin) and the per-method mean
    (bold) against the mean realized rate (dashed), and the right axis
    with the RMSE against the realized rates, drawn only at checkpoints
    where every trial has an estimate. Methods keep their colors and
    are direct-labeled at their line ends; every method appears in the
    right axis legend. Axis titles are kept short to fit the panels;
    the thin/bold distinction is left for the figure caption to
    explain.

    :param methods: methods in drawing order
    :param trajectories: per-method, per-trial estimate trajectories
    :param true_rates: realized rate per trial
    :param tolerance: RMSE drawn as the tolerance baseline
    :return: LaTeX code of the `tikzpicture`
    """
    checkpoints: list[int] = trajectories[methods[0]][0].checkpoints
    n_trials: int = len(true_rates)
    stats: dict[LexiconSelection, list[CheckpointStats]] = (
        aggregate_trajectories(methods, trajectories, true_rates)
    )
    mean_true: float = sum(true_rates) / len(true_rates)
    x_last: float = float(checkpoints[-1])

    values: list[float] = [mean_true] + [
        estimate[0]
        for method in methods
        for trajectory in trajectories[method]
        for estimate in trajectory.estimates
        if estimate is not None
    ]
    y_low: float = min(values)
    y_high: float = max(values)
    pad: float = 0.05 * ((y_high - y_low) or 1.0)
    y_min: float = y_low - pad
    y_max: float = y_high + pad

    lines: list[str] = [
        *_preamble([RATE_ESTIMATOR_BY_SELECTION[method] for method in methods]),
        "\\begin{tikzpicture}",
        *_begin_axis(
            [
                "name=rate",
                "width=.44\\linewidth",
                "height=.36\\linewidth",
                *AXIS_CHROME,
                f"xmin=0, xmax={x_last * 1.05:.1f}",
                f"ymin={y_min:.4f}, ymax={y_max:.4f}",
                "title={Rate estimate $\\hat{r}$}",
            ]
        ),
        # The mean realized rate baseline.
        "\\addplot[dashed, line width=0.8pt, forget plot] coordinates",
        "    {"
        f"{_coordinates([(0.0, mean_true), (x_last * 1.18, mean_true)])}"
        "};",
        f"\\node[anchor=south west, font=\\scriptsize] "
        f"at (axis cs:{checkpoints[0]:g},{mean_true:.4f}) {{true $r$}};",
    ]

    label_ends: list[tuple[str, float]] = []
    for method in methods:
        color: str = method_color_name(RATE_ESTIMATOR_BY_SELECTION[method])
        for trajectory in trajectories[method]:
            lines += _plot_segments(
                checkpoints,
                [
                    estimate[0] if estimate is not None else math.nan
                    for estimate in trajectory.estimates
                ],
                f"{color}, line width=0.5pt, opacity=0.3, forget plot",
            )
        means: list[float] = [
            stat.mean if stat.mean is not None else math.nan
            for stat in stats[method]
        ]
        lines += _plot_segments(
            checkpoints, means, f"{color}, line width=1.4pt, forget plot"
        )
        finite: list[float] = [
            value for value in means if not math.isnan(value)
        ]
        if finite:
            label_ends.append((str(method), finite[-1]))

    # Direct labels overflow into the gap between the two axes.
    lines += [
        _end_label(x_last, position, label, "font=\\scriptsize")
        for label, position in spread_label_positions(label_ends, y_min, y_max)
    ]
    lines.append("\\end{axis}")

    errors_by_method: dict[LexiconSelection, list[float]] = {
        method: [
            stat.rmse
            if stat.rmse is not None and stat.count == n_trials
            else math.nan
            for stat in stats[method]
        ]
        for method in methods
    }
    error_values: list[float] = [tolerance] + [
        error
        for errors in errors_by_method.values()
        for error in errors
        if not math.isnan(error)
    ]
    error_max: float = max(error_values)

    lines += _begin_axis(
        [
            "at={(rate.east)}, anchor=west, xshift=2cm",
            "width=.44\\linewidth",
            "height=.36\\linewidth",
            *AXIS_CHROME,
            f"xmin=0, xmax={x_last * 1.05:.1f}",
            f"ymin=0, ymax={error_max * 1.1:.4f}",
            "title={RMSE vs realized $r$}",
            "legend style={draw=none, fill=none, font=\\footnotesize}",
            "legend cell align=left",
        ]
    )

    # Legend images keep every method in the legend, even one whose
    # estimator never had an answer and draws no line.
    for method in methods:
        color = method_color_name(RATE_ESTIMATOR_BY_SELECTION[method])
        lines += [
            f"\\addlegendimage{{{color}, line width=1.4pt}}",
            f"\\addlegendentry{{{method}}}",
        ]

    lines += [
        "\\addplot[dashed, line width=0.8pt, forget plot] coordinates",
        "    {"
        f"{_coordinates([(0.0, tolerance), (x_last * 1.05, tolerance)])}"
        "};",
        f"\\node[anchor=south west, font=\\scriptsize] "
        f"at (axis cs:{checkpoints[0]:g},{tolerance:.4f}) {{tolerance}};",
    ]
    for method in methods:
        color = method_color_name(RATE_ESTIMATOR_BY_SELECTION[method])
        lines += _plot_segments(
            checkpoints,
            errors_by_method[method],
            f"{color}, line width=1.4pt, forget plot",
        )

    lines += ["\\end{axis}", "\\end{tikzpicture}", ""]
    return "\n".join(lines)
